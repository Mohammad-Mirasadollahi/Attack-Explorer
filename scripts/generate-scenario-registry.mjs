#!/usr/bin/env node
/**
 * Regenerates scenario package barrels and catalog aggregators from the filesystem.
 *
 * Usage:
 *   node scripts/generate-scenario-registry.mjs
 *   node scripts/generate-scenario-registry.mjs --check
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SCENARIOS_DIR = path.join(ROOT, 'modules/scenarios');
const CHECK = process.argv.includes('--check');

const SKIP_DIRS = new Set(['legacy']);

function read(file) {
  return fs.readFileSync(file, 'utf8');
}

function listPackages() {
  return fs
    .readdirSync(SCENARIOS_DIR, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && !SKIP_DIRS.has(entry.name))
    .map((entry) => entry.name)
    .filter((id) => fs.existsSync(path.join(SCENARIOS_DIR, id, 'scenario.ts')))
    .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

function alias(prefix, id) {
  return prefix + id.replace(/[^A-Za-z0-9_]/g, '_');
}

function classify(id) {
  const source = read(path.join(SCENARIOS_DIR, id, 'scenario.ts'));
  const legacy = /export const scenario:\s*LegacyDraftScenario\b/.test(source);
  const canonical = /export const scenario:\s*AttackScenario\b/.test(source);
  if (legacy === canonical) {
    throw new Error(
      `${id}/scenario.ts must export exactly one of AttackScenario or LegacyDraftScenario`
    );
  }
  return legacy ? 'legacy' : 'canonical';
}

function hasFile(id, name) {
  return fs.existsSync(path.join(SCENARIOS_DIR, id, name));
}

function renderIndex(id) {
  const lines = [`export { scenario } from './scenario';`];
  if (hasFile(id, 'step-guide.ts')) lines.push(`export { stepGuide } from './step-guide';`);
  if (hasFile(id, 'standard-patch.ts')) {
    lines.push(`export { standardPatch } from './standard-patch';`);
  }
  if (hasFile(id, 'choreography.ts')) lines.push(`export * from './choreography';`);
  if (hasFile(id, 'telemetry.ts')) lines.push(`export * from './telemetry';`);
  return `${lines.join('\n')}\n`;
}

function renderAllScenarios(packages) {
  const canonical = packages.filter((id) => classify(id) === 'canonical');
  const legacy = packages.filter((id) => classify(id) === 'legacy');
  const imports = packages
    .map(
      (id) =>
        `import { scenario as ${alias('s_', id)} } from './${id}/scenario';`
    )
    .join('\n');
  const list = (ids) => ids.map((id) => `  ${alias('s_', id)},`).join('\n');
  return `// Generated by scripts/generate-scenario-registry.mjs. Do not edit by hand.
import type { AttackScenario } from './types';
import type { LegacyDraftScenario } from './legacy/normalize-legacy-draft-scenario';
${imports}

export const CANONICAL_ATTACK_SCENARIOS: AttackScenario[] = [
${list(canonical)}
];

export const LEGACY_DRAFT_SCENARIOS: LegacyDraftScenario[] = [
${list(legacy)}
];
`;
}

function renderAllStepGuides(packages) {
  const guided = packages.filter((id) => hasFile(id, 'step-guide.ts'));
  const imports = guided
    .map(
      (id) =>
        `import { stepGuide as ${alias('g_', id)} } from './${id}/step-guide';`
    )
    .join('\n');
  const entries = guided
    .map((id) => `  '${id}': ${alias('g_', id)},`)
    .join('\n');
  return `// Generated by scripts/generate-scenario-registry.mjs. Do not edit by hand.
import type { RawScenarioStepGuideData } from '@/modules/scenarios/contracts';
${imports}

export const STATIC_SCENARIO_STEP_GUIDES: Record<string, RawScenarioStepGuideData> = {
${entries}
};
`;
}

function renderAllPatches(packages) {
  const patched = packages.filter((id) => hasFile(id, 'standard-patch.ts'));
  const imports = patched
    .map(
      (id) =>
        `import { standardPatch as ${alias('p_', id)} } from './${id}/standard-patch';`
    )
    .join('\n');
  const entries = patched
    .map((id) => `  '${id}': ${alias('p_', id)},`)
    .join('\n');
  return `// Generated by scripts/generate-scenario-registry.mjs. Do not edit by hand.
import type { CategoryStandardPatchMap } from '@/modules/scenarios/contracts';
${imports}

export const ALL_CATEGORY_STANDARD_PATCHES: CategoryStandardPatchMap = {
${entries}
};
`;
}

function writeOrCheck(file, contents) {
  const current = fs.existsSync(file) ? read(file) : null;
  if (CHECK) {
    if (current !== contents) {
      console.error(`registry drift: ${path.relative(ROOT, file)}`);
      return false;
    }
    return true;
  }
  if (current !== contents) fs.writeFileSync(file, contents);
  return true;
}

const packages = listPackages();
let ok = true;
ok &&= writeOrCheck(
  path.join(SCENARIOS_DIR, 'all-scenarios.ts'),
  renderAllScenarios(packages)
);
ok &&= writeOrCheck(
  path.join(SCENARIOS_DIR, 'all-step-guides.ts'),
  renderAllStepGuides(packages)
);
ok &&= writeOrCheck(
  path.join(SCENARIOS_DIR, 'all-standard-patches.ts'),
  renderAllPatches(packages)
);
for (const id of packages) {
  ok &&= writeOrCheck(
    path.join(SCENARIOS_DIR, id, 'index.ts'),
    renderIndex(id)
  );
}

if (!ok) {
  console.error('Scenario registry is out of date. Run: node scripts/generate-scenario-registry.mjs');
  process.exit(1);
}

if (!CHECK) {
  console.log(`registry updated for ${packages.length} scenario packages`);
}
