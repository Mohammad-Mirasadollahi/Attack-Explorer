/**
 * Extracts canonical Event IDs from a TelemetryEvent and correlates
 * Windows Security Event ID 4688 whenever Sysmon Event ID 1 (Process Creation) occurs.
 */
export function extractEventIdsFromLog(
  event: TelemetryEvent
): EventIdBadgeInfo[] {
  const foundIds = new Set<string>();

  // 1. Match <EventID>N</EventID> or EventID: N or EID N
  const regexes = [
    /<EventID>(\d+)<\/EventID>/gi,
    /EventID[:\s=]+(\d+)/gi,
    /\bEID\s+(\d+)/gi,
  ];
  const combinedSource = `${event.protocolOrEventId} ${event.info} ${event.rawLog}`;

  for (const rx of regexes) {
    let match: RegExpExecArray | null;
    while ((match = rx.exec(combinedSource)) !== null) {
      foundIds.add(match[1]);
    }
  }

  // Correlate Windows Security Event ID 4688 with Sysmon Event ID 1 (Process Creation)
  if (foundIds.has('1')) {
    foundIds.add('4688');
  }

  // Also correlate Sysmon EID 8 on Remote Thread / Reflective injection steps if Win32 API
  if (
    foundIds.size === 0 &&
    /CreateProcess|svchost\.exe|vssadmin/i.test(combinedSource)
  ) {
    foundIds.add('1');
    foundIds.add('4688');
  }

  const result: EventIdBadgeInfo[] = [];
  for (const id of foundIds) {
    const meta = EVENT_ID_METADATA[id] || {
      channel: 'SIEM / Telemetry Stream',
      label: `Event ID ${id}`,
      description: `Security telemetry event identifier ${id}.` };
    result.push({
      id,
      label: meta.label,
      channel: meta.channel,
      isPrimaryHighlight: id === '1' || id === '4688' || id === '25' || id === '10' || id === '4769' || id === '4624',
      description: meta.description });
  }

  return result;
}

/**
 * Prepends active environment forensic header and appends correlated Windows Security 4688 audit log
 * when Sysmon EID 1 is present so SOC analysts can inspect both Sysmon EID 1 and Security EID 4688
 * tagged with the Current Active Environment.
 */
export function buildCorrelatedRawLog(
  event: TelemetryEvent,
  activeEnvironment: ActiveEnvironmentId = DEFAULT_ACTIVE_ENVIRONMENT
): string {
  const profile = getActiveEnvironmentProfile(activeEnvironment);
  const envHeader = `[ACTIVE_ENVIRONMENT: ${profile.badgeLabel} | Tag: ${profile.telemetryTag} | Host: ${profile.hostname} (${profile.ipSubnet})]`;

  let baseLog = event.rawLog;
  if (activeEnvironment !== 'WORKSTATION') {
    baseLog = baseLog.replace(
      /<Computer>[^<]+<\/Computer>/gi,
      `<Computer>${profile.hostname}</Computer>`
    );
  }

  if (
    /<EventID>1<\/EventID>/i.test(baseLog) &&
    !/4688/.test(baseLog)
  ) {
    const pidMatch = baseLog.match(/<Data Name="ProcessId">([^<]+)<\/Data>/);
    const imgMatch = baseLog.match(/<Data Name="Image">([^<]+)<\/Data>/);
    const cmdMatch = baseLog.match(
      /<Data Name="CommandLine">([^<]+)<\/Data>/
    );
    const parentImgMatch = baseLog.match(
      /<Data Name="ParentImage">([^<]+)<\/Data>/
    );

    const pid = pidMatch ? pidMatch[1] : '4892';
    const img = imgMatch ? imgMatch[1] : 'C:\\Windows\\System32\\svchost.exe';
    const cmd = cmdMatch ? cmdMatch[1] : img;
    const parentImg = parentImgMatch
      ? parentImgMatch[1]
      : 'C:\\Users\\s.ahmadi\\Downloads\\Invoice_Q4.exe';

    return `${envHeader}
${baseLog}

<!-- Correlated Windows Security Audit Log (Event ID 4688 · ${profile.telemetryTag}) -->
<Event xmlns="http://schemas.microsoft.com/win/2004/08/events/event">
  <System>
    <Provider Name="Microsoft-Windows-Security-Auditing" Guid="{54849625-5478-4994-A5BA-3E3B0328C30D}"/>
    <EventID>4688</EventID>
    <Channel>Security</Channel>
    <Computer>${profile.hostname}</Computer>
  </System>
  <EventData>
    <Data Name="ActiveEnvironment">${profile.badgeLabel} (${profile.telemetryTag})</Data>
    <Data Name="NewProcessId">0x131c (${pid})</Data>
    <Data Name="NewProcessName">${img}</Data>
    <Data Name="TokenElevationType">%%1936 (Type 1 - Full Token)</Data>
    <Data Name="CommandLine">${cmd}</Data>
    <Data Name="CreatorProcessName">${parentImg}</Data>
  </EventData>
</Event>`;
  }

  return `${envHeader}\n${baseLog}`;
}

/**
 * Builds the step-by-step enriched log list for the currently active scenario,
 * tagged with the Current Active Environment.
 */
export function buildCorrelatedStepLogs(
  scenario: AttackScenario,
  activeStageIndex: number,
  activeEnvironment: ActiveEnvironmentId = DEFAULT_ACTIVE_ENVIRONMENT
): EnrichedStepLog[] {
  const profile = getActiveEnvironmentProfile(activeEnvironment);
  return scenario.telemetry.map((rawEvent) => {
    const event = tagTelemetryEventWithEnvironment(rawEvent, activeEnvironment);
    const stage = scenario.stages.find((s) => s.index === event.stageIndex);
    const stageTitle: string = stage
      ? stage.title
      : `STAGE ${event.stageIndex}`;

    const isActiveStep =
      activeStageIndex === 0 || event.stageIndex === activeStageIndex;

    return {
      id: event.id,
      stageIndex: event.stageIndex,
      stageTitle,
      event,
      activeEnvironmentId: activeEnvironment,
      environmentProfile: profile,
      environmentBadge: profile.badgeLabel,
      environmentTag: profile.telemetryTag,
      isActiveStep,
      eventIds: extractEventIdsFromLog(event),
      correlatedRawLog: buildCorrelatedRawLog(event, activeEnvironment) };
  });
}

/**
 * Tokenizes a single raw log line to highlight Event IDs (like 4688 or 1),
 * active environment tags, and critical forensic indicators without using innerHTML.
 */
export function tokenizeLogLineForHighlight(line: string): LogLineToken[] {
  const pattern =
    /(<EventID>\d+<\/EventID>|EventID[:\s=]+\d+|Sysmon EID \d+|WinSec EID \d+|ENV:[A-Z0-9/_-]+|ACTIVE_ENVIRONMENT:\s*[^|\]]+|0x1FFFFF|CREATE_SUSPENDED|NtUnmapViewOfSection|VirtualAllocEx|WriteProcessMemory|SetThreadContext|Image is replaced|\$\{[\w:$//{}.-]+\}|vssadmin\.exe Delete Shadows|0x17)/g;

  const tokens: LogLineToken[] = [];
  let lastIdx = 0;
  let match: RegExpExecArray | null;

  while ((match = pattern.exec(line)) !== null) {
    if (match.index > lastIdx) {
      tokens.push({
        text: line.slice(lastIdx, match.index),
        kind: 'plain' });
    }

    const matchedText = match[0];
    const isEventId = /EventID|EID|ACTIVE_ENVIRONMENT|ENV:/i.test(matchedText);
    tokens.push({
      text: matchedText,
      kind: isEventId ? 'event_id' : 'indicator' });

    lastIdx = match.index + matchedText.length;
  }

  if (lastIdx < line.length) {
    tokens.push({
      text: line.slice(lastIdx),
      kind: 'plain' });
  }

  return tokens.length > 0 ? tokens : [{ text: line, kind: 'plain' }];
}

